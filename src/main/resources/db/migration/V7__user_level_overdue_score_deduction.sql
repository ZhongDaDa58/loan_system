-- =============================================================================
-- V7：逾期扣分改为「用户维度」（逾期处理功能升级 第 8 步 / 决策 ①）
-- =============================================================================
-- 背景：第 5 步实现逾期扣信用分时，幂等标记放在 monthly_repayment.score_deducted_level
--       （**期次级**），也就是每一期各自扣分。当时我自己就发现这有问题
--       （提交 4aedd71 里写了"待产品确认"），现在改成用户维度。
--
-- 为什么要改（旧行为的具体问题）：
--
--   ① 同一违约事件被重复计罚
--      分期贷款逾期 10 期，本质是**一次违约**（这个人还不上钱了），
--      但按旧逻辑会扣 10 次 → 直接扣到下限 300，失去区分度。
--
--   ② 权重倒挂
--      1 笔逾期 60 天（M3）：扣 50 分
--      10 笔各逾期 5 天（全 M1）：扣 100 分 → 直接打到底
--      后者的实际风险明显低于前者，扣分却更重。
--
--   ③ 与设计文档不符
--      §3.5 写的扣分事件是"首次进入 M1 / M1→M2 / M2→M3"，
--      这是**用户维度**的等级跃迁，不是"每期各算一次"。
--
-- 改动：
--   在 user_credit_score 上增加 last_overdue_deduct_level，
--   记录"该用户已按哪个等级扣过分"。只有当用户的**最高逾期等级**比它更高时才扣。
--
--   效果：3 笔逾期（M1+M2+M3）从「扣 80 分」变成「按最高等级 M3 扣 50 分」。
--
-- ⚠️ monthly_repayment.score_deducted_level 保留不删：
--    a) 删列有风险（可能有其他地方在读）；
--    b) 它现在可以当"这一期上次是按哪一级扣的"历史记录用。
--    但**幂等判断已经不再依赖它**，改由本迁移新增的列负责。
--
-- 回滚：ALTER TABLE user_credit_score DROP COLUMN last_overdue_deduct_level;
--       （回滚后幂等判断会退回期次级逻辑，需要同步回滚 OverdueScoreDeductor）
-- =============================================================================

ALTER TABLE user_credit_score
    ADD COLUMN last_overdue_deduct_level VARCHAR(8) NULL
        COMMENT '该用户上次逾期扣分对应的最高等级 M1/M2/M3（用户维度幂等标记）'
        AFTER credit_score;
